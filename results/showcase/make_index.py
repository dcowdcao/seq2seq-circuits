#!/usr/bin/env python
"""Write results/showcase/README.md: the table of the five showcase circuits, generated from
each example's circuit.json (no number in it is typed by hand).

    python results/showcase/make_index.py
"""
from __future__ import annotations

import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import showcase_spec as S  # noqa: E402

INTRO = """# Showcase: one circuit per class

Five small seq2seq transformers, each trained on one algorithm over 10-digit inputs, with one
circuit per circuit class. Every example directory holds the selected circuit
(`circuit.json`: components, size, faithfulness, selection score and the command that
re-evaluates it), the full candidate table (`candidates.json`), a figure of the circuit on the
model's architecture (`figure.png`) and a card (`README.md`) with the algorithm, the
architecture and example inputs and outputs. The trained checkpoints are not included; each card
records the path and sha256 of the checkpoint its numbers were computed on.

Candidate circuits are found with EAP-IG (edge attribution patching with integrated
gradients): the top-n edges for the pipeline's canonical ladder of n (fixed fractions of the
model's edges; for the probe-based classes, of the edges that can reach the probe), plus, for
the Domain, Contrast and Suppression examples, the candidates the pipeline's smallest-circuit
stage adds (one from its search and, by default, one round of midpoint refinement between
adjacent rungs).{probe_note} The reported circuit is the candidate above
its class's faithfulness floor that maximizes (1 − nodes/nodes_full) · (1 − edges/edges_full),
chosen by `pipeline/find_circuits/evaluate_circuit.py --select`. Nothing guarantees that a
smaller faithful circuit does not exist: these are the circuits this method finds, not ground
truth.

![The five circuits](overview.png)
"""

OUTRO = """
`a` is faithfulness as defined for the class (see each card); a circuit qualifies when
`a` > floor ({floors}). The paired classes use a lower floor because their `a` is a product of
two accuracies. Nodes are attention heads plus one node per MLP/MoE block; edges are
writer→reader connections with each head's Q, K and V inputs counted separately. Counts are
out of the model's full graph; for the probe-based classes the full graph is cut at the probe
layer, because components above it cannot affect the probe. `--select` picks the winner on
the same (seed 0) rows it reports, so each shipped circuit is also re-evaluated on held-out
rows: `--seed 1` draws fresh evaluation rows and fresh mean-reference rows, with everything
else identical (`heldout_seed1.json` in each example directory). Candidate paths under
`pipeline/circuits_data/` are generated by `reproduce.py --full` and are gitignored.

## Reproduce

```bash
# re-evaluate the stored circuits (seed 0) and the held-out files (seed 1); check every number
python results/showcase/reproduce.py --verify
# re-run discovery + selection + held-out from the checkpoints, then figures, cards, this page
python results/showcase/reproduce.py --full
```

{runtime}
Exact per-stage commands and measured CPU runtimes: [COMMANDS.md](COMMANDS.md).
"""


def arch(c: dict) -> str:
    a = c["architecture"]
    ff = ""
    if not a.get("attn_only", True):
        ff = (f", MoE {a['num_experts']}×{a['d_mlp']} top-{a['experts_per_token']}"
              if a.get("num_experts") else f", MLP {a['d_mlp']}")
    return f"{a['n_layers']}L × {a['n_heads']}H, width {a['d_model']}{ff}"


def runtime_note(done: list) -> str:
    """The measured wall time of --full: the sum over every command in runtimes.json."""
    total = 0
    for ex in done:
        p = os.path.join(ex.dir, "runtimes.json")
        if os.path.exists(p):
            total += sum(s["wall_seconds"] for steps in json.load(open(p)).values() for s in steps)
    h, m = divmod(round(total / 60), 60)
    return (f"Measured wall time of `--full` for the files here: {h} h {m:02d} min of CPU "
            "commands in total (the sum over every example's `runtimes.json`, on a shared "
            "16-core machine; the examples are independent and can run in parallel).\n")


def probe_note(done: list) -> str:
    """The sentence about examples with extra explicit EAP-IG rungs (from showcase_spec)."""
    notes = []
    for ex in done:
        if ex.probe_topns:
            n = json.load(open(os.path.join(ex.dir, "circuit.json")))["n_edges_full"]
            notes.append(f" For the {ex.cls}, whose probe only {n} edges can reach, the explicit "
                         f"rungs {', '.join(map(str, ex.probe_topns))} are added, because a "
                         f"4-rung ladder over {n} edges is too coarse.")
    return "".join(notes)


def main() -> None:
    rows = ["| class | model | algorithm | architecture | nodes | edges | a | "
            "held-out a (seed 1) | floor | |",
            "|---|---|---|---|---|---|---|---|---|---|"]
    done = [ex for ex in S.EXAMPLES if os.path.exists(os.path.join(ex.dir, "circuit.json"))]
    for ex in done:
        c = json.load(open(os.path.join(ex.dir, "circuit.json")))
        mark = "" if c["passes"] else " (below floor)"
        hp = os.path.join(ex.dir, "heldout_seed1.json")
        h = json.load(open(hp)) if os.path.exists(hp) else None
        ho = "–" if h is None else (f"{h['a']:.3f}" + ("" if h["passes"] else " (below floor)"))
        rows.append(
            f"| {ex.cls} | `{ex.model}` | {ex.blurb} | {arch(c)} | "
            f"{c['n_nodes']}/{c['n_nodes_full']} | {c['n_edges']}/{c['n_edges_full']} | "
            f"{c['a']:.3f}{mark} | {ho} | {c['floor']:.2f} | "
            f"[card]({ex.key}/README.md) · [figure]({ex.key}/figure.png) |")
    floors = {}
    for ex in done:
        c = json.load(open(os.path.join(ex.dir, "circuit.json")))
        floors.setdefault(c["floor"], []).append(ex.cls)
    floor_txt = "; ".join(f"{fl:.2f} for {', '.join(cls)}" for fl, cls in sorted(floors.items(),
                                                                                 reverse=True))
    with open(os.path.join(S.HERE, "README.md"), "w") as f:
        f.write(INTRO.format(probe_note=probe_note(done)) + "\n" + "\n".join(rows) + "\n"
                + OUTRO.format(floors=floor_txt, runtime=runtime_note(done)))
    print("wrote README.md")


if __name__ == "__main__":
    main()
